CREATE DATABASE IF NOT EXISTS uniride CHARACTER SET utf8mb4;
USE uniride;
-- Gestion des utilisateurs
CREATE TABLE role (ID_ROLE INT AUTO_INCREMENT PRIMARY KEY, NOM_ROLE VARCHAR(30) NOT NULL UNIQUE);
CREATE TABLE app_user (
  ID_USER INT AUTO_INCREMENT PRIMARY KEY, NOM VARCHAR(50), PRENOM VARCHAR(50),
  EMAIL VARCHAR(100) UNIQUE NOT NULL, PASSWORD VARCHAR(255) NOT NULL, TELEPHONE VARCHAR(20),
  ADRESSE VARCHAR(150), DATE_INSCRIPTION DATETIME, STATUT VARCHAR(20) DEFAULT 'ACTIF', EMAIL_VERIFIE TINYINT(1) DEFAULT 0);
CREATE TABLE user_role (ID_USER INT, ID_ROLE INT, PRIMARY KEY (ID_USER, ID_ROLE),
  FOREIGN KEY (ID_USER) REFERENCES app_user(ID_USER), FOREIGN KEY (ID_ROLE) REFERENCES role(ID_ROLE));
-- Gestion des véhicules
CREATE TABLE vehicle (
  ID_VEHICLE INT AUTO_INCREMENT PRIMARY KEY, ID_USER INT, MARQUE VARCHAR(50), MODELE VARCHAR(50), IMMATRICULATION VARCHAR(20),
  COULEUR VARCHAR(20), ANNEE INT, NB_PLACES INT, TYPE_VEHICLE VARCHAR(30), STATUT VARCHAR(20) DEFAULT 'ACTIF',
  FOREIGN KEY (ID_USER) REFERENCES app_user(ID_USER));
CREATE TABLE vehicle_photo (ID_PHOTO INT AUTO_INCREMENT PRIMARY KEY, ID_VEHICLE INT, URL_PHOTO VARCHAR(255), EST_PRINCIPALE TINYINT(1) DEFAULT 0, DATE_AJOUT DATETIME,
  FOREIGN KEY (ID_VEHICLE) REFERENCES vehicle(ID_VEHICLE));
-- Gestion des trajets
CREATE TABLE trip (
  ID_TRIP INT AUTO_INCREMENT PRIMARY KEY, ID_USER INT, ID_VEHICLE INT NULL, LIEU_DEPART VARCHAR(100), LIEU_ARRIVEE VARCHAR(100),
  DATE_DEPART DATETIME, DATE_ARRIVEE DATETIME NULL, PRIX DECIMAL(6,2), NB_PLACES_DISPONIBLES INT, DESCRIPTION TEXT, STATUT VARCHAR(20),
  FOREIGN KEY (ID_USER) REFERENCES app_user(ID_USER), FOREIGN KEY (ID_VEHICLE) REFERENCES vehicle(ID_VEHICLE));
CREATE TABLE trip_stop (ID_STOP INT AUTO_INCREMENT PRIMARY KEY, ID_TRIP INT, LIEU_STOP VARCHAR(100), HEURE_PASSAGE TIME, ORDRE_STOP INT,
  FOREIGN KEY (ID_TRIP) REFERENCES trip(ID_TRIP));
-- Réservations et paiements
CREATE TABLE reservation (ID_RESERVATION INT AUTO_INCREMENT PRIMARY KEY, ID_USER INT, ID_TRIP INT, DATE_RESERVATION DATETIME, NB_PLACES INT, STATUT VARCHAR(20),
  FOREIGN KEY (ID_USER) REFERENCES app_user(ID_USER), FOREIGN KEY (ID_TRIP) REFERENCES trip(ID_TRIP));
CREATE TABLE payment (ID_PAYMENT INT AUTO_INCREMENT PRIMARY KEY, ID_RESERVATION INT, MONTANT DECIMAL(6,2), DATE_PAYMENT DATETIME, MODE_PAYMENT VARCHAR(30), STATUT VARCHAR(20),
  FOREIGN KEY (ID_RESERVATION) REFERENCES reservation(ID_RESERVATION));
-- Évaluations et favoris
CREATE TABLE review (ID_REVIEW INT AUTO_INCREMENT PRIMARY KEY, ID_USER INT, ID_TRIP INT, NOTE INT, COMMENTAIRE TEXT, DATE_REVIEW DATETIME,
  FOREIGN KEY (ID_USER) REFERENCES app_user(ID_USER), FOREIGN KEY (ID_TRIP) REFERENCES trip(ID_TRIP));
CREATE TABLE favorite (ID_FAVORITE INT AUTO_INCREMENT PRIMARY KEY, ID_USER INT, ID_TRIP INT, DATE_AJOUT DATETIME,
  FOREIGN KEY (ID_USER) REFERENCES app_user(ID_USER), FOREIGN KEY (ID_TRIP) REFERENCES trip(ID_TRIP));
-- Communication et support
CREATE TABLE conversation (ID_CONVERSATION INT AUTO_INCREMENT PRIMARY KEY, ID_USER1 INT, ID_USER2 INT, TYPE_CONVERSATION VARCHAR(30), DATE_CREATION DATETIME, STATUT VARCHAR(20),
  FOREIGN KEY (ID_USER1) REFERENCES app_user(ID_USER), FOREIGN KEY (ID_USER2) REFERENCES app_user(ID_USER));
CREATE TABLE message (ID_MESSAGE INT AUTO_INCREMENT PRIMARY KEY, ID_CONVERSATION INT, ID_EXPEDITEUR INT, CONTENU TEXT, DATE_ENVOI DATETIME, EST_LU TINYINT(1) DEFAULT 0,
  FOREIGN KEY (ID_CONVERSATION) REFERENCES conversation(ID_CONVERSATION), FOREIGN KEY (ID_EXPEDITEUR) REFERENCES app_user(ID_USER));
CREATE TABLE support_request (ID_SUPPORT INT AUTO_INCREMENT PRIMARY KEY, ID_USER INT, ID_CONVERSATION INT NULL, SUJET VARCHAR(150), DESCRIPTION TEXT, DATE_DEMANDE DATETIME, STATUT VARCHAR(20),
  FOREIGN KEY (ID_USER) REFERENCES app_user(ID_USER), FOREIGN KEY (ID_CONVERSATION) REFERENCES conversation(ID_CONVERSATION));
-- Offres et fidélité
CREATE TABLE offre (ID_OFFRE INT AUTO_INCREMENT PRIMARY KEY, CODE VARCHAR(30) UNIQUE, DESCRIPTION VARCHAR(255), POURCENTAGE INT, DATE_EXPIRATION DATE, MAX_UTILISATIONS INT, STATUT VARCHAR(20));
CREATE TABLE fidelite_compte (ID_USER INT PRIMARY KEY, POINTS INT DEFAULT 0, NIVEAU VARCHAR(20) DEFAULT 'BRONZE', FOREIGN KEY (ID_USER) REFERENCES app_user(ID_USER));

